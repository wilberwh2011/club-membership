// Builds the Apps Script project into dist/ (plan.md "Project Structure", research R8):
//   dist/Code.js          server bundle (IIFE exposing `__registry`) + one top-level stub per entry point
//   dist/<page>.html      src/ui/pages/<page>.html with styles, translations and client script inlined
//   dist/appsscript.json  copied manifest
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const DIST = join(ROOT, 'dist');

export const PAGES = ['register', 'signin', 'app'];
// Editor-run and routing entry points that always get a global stub, registered or not.
export const FIXED_ENTRY_POINTS = ['doGet', 'setup', 'seedSyntheticMembers', 'runAdapterChecks'];
const LOCALES = ['en', 'zh-Hans'];

function loadTranslations() {
  const translations = {};
  for (const locale of LOCALES) {
    const file = join(SRC, 'i18n', `${locale}.json`);
    if (!existsSync(file)) throw new Error(`Missing translation file ${file}`);
    translations[locale] = JSON.parse(readFileSync(file, 'utf8'));
  }
  return translations;
}

// JSON safe to embed in an HTML <script> element.
function scriptSafeJson(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

async function bundleServer() {
  const result = await build({
    entryPoints: [join(SRC, 'server', 'main.ts')],
    bundle: true,
    format: 'iife',
    globalName: '__registry',
    target: 'es2020',
    platform: 'neutral',
    write: false,
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

// Loads the bundle in an empty sandbox (no Apps Script globals) and reads the registered endpoint names.
export function registryNames(bundle) {
  const sandbox = {};
  vm.runInNewContext(`${bundle}\nthis.__exports = __registry;`, sandbox);
  const registry = sandbox.__exports.registry;
  if (!Array.isArray(registry)) throw new Error('src/server/main.ts must export `registry` (an array)');
  return registry.map((entry) => entry.name);
}

export function stubSource(names) {
  return [...new Set([...FIXED_ENTRY_POINTS, ...names])]
    .map((name) =>
      name === 'doGet'
        ? 'function doGet(e) { return __registry.doGet(e); }'
        : `function ${name}() { return __registry.dispatch('${name}', Array.prototype.slice.call(arguments)); }`,
    )
    .join('\n');
}

async function bundleClient(page) {
  const entry = join(SRC, 'ui', 'client', `${page}.ts`);
  if (!existsSync(entry)) return '';
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    platform: 'browser',
    write: false,
    logLevel: 'silent',
  });
  // Keep the inlined script from closing its own <script> element.
  return result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
}

function readStyles() {
  const dir = join(SRC, 'ui', 'styles');
  if (!existsSync(dir)) return '';
  return readdirSync(dir)
    .filter((f) => f.endsWith('.css'))
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8'))
    .join('\n');
}

function inject(html, marker, fallbackTag, content) {
  const placeholder = `<!-- @${marker} -->`;
  if (html.includes(placeholder)) return html.replace(placeholder, () => content);
  return html.replace(fallbackTag, () => `${content}\n${fallbackTag}`);
}

async function buildPage(page, styles, translations) {
  const template = join(SRC, 'ui', 'pages', `${page}.html`);
  if (!existsSync(template)) throw new Error(`Missing page template ${template}`);
  let html = readFileSync(template, 'utf8');
  html = inject(html, 'styles', '</head>', `<style>\n${styles}\n</style>`);
  html = inject(html, 'i18n', '</body>', `<script>var __I18N = ${scriptSafeJson(translations)};</script>`);
  const script = await bundleClient(page);
  html = inject(html, 'script', '</body>', script ? `<script>\n${script}</script>` : '');
  return html;
}

export async function runBuild() {
  const translations = loadTranslations();
  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(DIST, { recursive: true });

  const bundle = await bundleServer();
  const names = registryNames(bundle);
  const code = [
    '// Generated by scripts/build.mjs. Do not edit.',
    `var __I18N = ${JSON.stringify(translations)};`,
    bundle,
    stubSource(names),
    '',
  ].join('\n');
  writeFileSync(join(DIST, 'Code.js'), code);

  const styles = readStyles();
  for (const page of PAGES) {
    writeFileSync(join(DIST, `${page}.html`), await buildPage(page, styles, translations));
  }
  copyFileSync(join(SRC, 'appsscript.json'), join(DIST, 'appsscript.json'));
  return { names };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  runBuild().then(
    ({ names }) => process.stdout.write(`Built dist/ (${names.length} registered endpoints)\n`),
    (err) => {
      process.stderr.write(`Build failed: ${err.message}\n`);
      process.exit(1);
    },
  );
}
